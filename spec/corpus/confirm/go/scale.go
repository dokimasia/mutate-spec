package fixture

// double returns twice n.
func double(n int) int {
	return n * 2
}

// half returns n divided by 2, rounded toward zero.
func half(n int) int {
	return n / 2
}

// triple returns three times n.
func triple(n int) int {
	return n * 3
}

// quarter returns n divided by 4, rounded toward zero.
func quarter(n int) int {
	return n / 4
}
